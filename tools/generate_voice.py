"""Compile reviewed command templates into literal-only, deterministic patterns."""
import collections
import json
import re
from localize import ROOT, LOCALES

ACTIONS={'addSupply':'ADD_SUPPLY','expiry':'EXPIRY','contacts':'CONTACTS','plans':'PLANS',
         'checklists':'CHECKLISTS','quantity':'QUANTITY','inspection':'INSPECTION','reminder':'REMINDER'}
SLOTS=re.compile(r'\{[^{}]+\}')


def validated_templates(queue):
    translated=queue.get('translations')
    if not queue.get('reviewer') or not isinstance(translated,dict) or set(translated)!=set(ACTIONS):
        raise ValueError('Complete reviewed intent set required: '+queue['locale'])
    result=[]
    for action in ACTIONS:
        expected=collections.Counter(SLOTS.findall(queue['intents'][action][0]))
        if sum(expected.values())>1:raise ValueError('Only single-slot commands are supported')
        forms=translated[action]
        if not isinstance(forms,list) or not forms:raise ValueError('Missing command templates')
        for template in forms:
            if not isinstance(template,str) or not template.strip() or '\n' in template or len(template)>500:
                raise ValueError('Invalid command template')
            if collections.Counter(SLOTS.findall(template))!=expected:
                raise ValueError('Command slots changed: '+queue['locale']+':'+action)
            result.append((ACTIONS[action],template))
    return result


def main():
    quote=lambda text:json.dumps(text,ensure_ascii=False).replace('$','\\$')
    lines=['package com.preptrove.app','// Generated by tools/generate_voice.py; templates are AI-reviewed, not device certification.',
           'internal val voicePatterns:Map<String,List<VoicePattern>> = mapOf(']
    total=0
    for locale in LOCALES:
        queue=json.loads((ROOT/'localization/voice-queues'/(locale+'.json')).read_text(encoding='utf-8'))
        patterns=validated_templates(queue);total+=len(patterns)
        lines.append(quote(locale)+' to listOf('+','.join('VoicePattern(VoiceAction.'+action+','+quote(template)+')' for action,template in patterns)+'),')
    lines.append(')')
    (ROOT/'app/src/main/java/com/preptrove/app/VoicePatterns.kt').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print('Validated',total,'templates across',len(LOCALES),'locales. Speech-engine support remains device dependent.')


if __name__=='__main__':main()
